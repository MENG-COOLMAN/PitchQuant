def check_output(text):
    missing = []
    for bid, pat, hint, level in REQUIRED_BLOCKS:
        if not re.search(pat, text, re.I):
            missing.append((bid, hint, level))
    return missing

def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return
    src = sys.argv[1]
    if os.path.exists(src):
        text = open(src, encoding='utf-8', errors='ignore').read()
    else:
        text = src  # 直接文本
    missing = check_output(text)
    print('=' * 60)
    print('output_checker.py — 输出完整性校验(2026-09-02)')
    print('=' * 60)
    if not missing:
        print('✅ 全部必填块通过——输出完整')
    else:
        print('🔴 缺失 %d 项(缺失=分析未完成·必须补齐):' % len(missing))
        for bid, hint, level in missing:
            print('  [%s][%s] %s' % (bid, level, hint))
        print('=' * 60)
        print('🔴执行纪律: 校验不过=禁止交付·补齐后重跑至全过(编译期强制·非事后提醒)')
        return 1
    return 0

if __name__ == '__main__':
    sys.exit(main())
