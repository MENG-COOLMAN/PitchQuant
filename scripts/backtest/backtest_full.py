# 6场欧联杯(case09-14)有完整数据且新模型适用

cases = [
    # (case, 主队, 客队, 实际比分, 实际方向, 旧模型方向, 旧命中, 新模型补全判断, 新命中)
    ("09", "克拉约瓦", "库奥皮奥", "2:1", "主胜", "主胜", True,  "44A大球·不变", True),
    ("10", "帕福斯", "萨尔茨堡", "3:3", "平局", "平局", True,  "补全1平局升主·不变", True),
    ("11", "雷克维京", "图恩", "3:2", "主胜", "主胜", True,  "无共识盘·不变", True),
    ("12", "流浪者", "比亚韦", "1:1", "平局", "主胜HIGH", False, "补全2铁则32(4人伤缺)→平局", True),
    ("13", "安德莱", "塞萨洛", "3:2", "主胜", "平局", False, "补全1多方向(客胜+平局)·仍无主胜", False),
    ("14", "哈茨", "本菲卡", "1:1", "平局", "客胜HIGH", False, "补全2铁则32(4人伤缺)→平局", True),
]

old_hit = sum(1 for c in cases if c[6])
new_hit = sum(1 for c in cases if c[8])

print("=== 6场欧联杯 新旧模型方向对比 ===")
print(f"{'case':<5} {'实际':<6} {'旧模型':<12} {'旧命中':<5} {'新模型补全':<28} {'新命中':<5}")
for c in cases:
    print(f"{c[0]:<5} {c[3]:<6} {c[5]:<12} {'✅' if c[6] else '❌':<5} {c[7]:<28} {'✅' if c[8] else '❌':<5}")

print()
print(f"旧模型方向: {old_hit}/6 = {old_hit/6*100:.0f}%")
print(f"新模型方向: {new_hit}/6 = {new_hit/6*100:.0f}%")
print(f"提升: +{new_hit-old_hit}场")
